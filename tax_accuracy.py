def check_generated(answer):
    """Cheap fail-closed review, not a guarantee of tax-law correctness."""
    a = n(answer)
    if not a.strip():
        return False, "empty"
    if anyof(a, ("720 میلیارد تومان", "۷۲۰ میلیارد تومان", "مالیات 72 میلیارد تومان", "مالیات ۷۲ میلیارد تومان")):
        return False, "confused sales ceiling with tax"
    if anyof(a, ("98 درصد مالیات", "98% مالیات", "2 درصد مالیات ثابت", "2% مالیات")):
        return False, "confused penalties with tax rate"
    for m in re.finditer(r"صفحه(?:های)?\s*([0-9]+)", a):
        if int(m.group(1)) not in range(1, 7):
            return False, "invalid page citation"
    for m in re.finditer(r"بند\s*([0-9]+)", a):
        if int(m.group(1)) not in range(1, 20):
            return False, "invalid clause citation"
    if not anyof(a, ("مستند:", "منبع:", "بند ", "صفحه ", "در دستورالعمل مشخص نشده", "در این دستورالعمل", "طبق اطلاع")):
        return False, "missing source reference"
    return True, "ok"


